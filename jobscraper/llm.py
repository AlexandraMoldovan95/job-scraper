"""One structured Claude call (Pydantic output), shared by the CV generator and the LinkedIn import."""

from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import Any, Generic, TypeVar

import anthropic
from pydantic import BaseModel

from jobscraper.config import LLMConfig
from jobscraper.keys import ANTHROPIC_API_KEY, KeyStore

log = logging.getLogger(__name__)

# Server-side refusal fallback: on a policy decline the API reruns the request on a
# suitable model inside the same call. Only these models accept the "default" form.
FALLBACK_BETA = "server-side-fallback-2026-07-01"
FALLBACK_MODELS = {"claude-fable-5-1", "claude-opus-5-5", "claude-opus-5", "claude-sonnet-5-5"}

T = TypeVar("T", bound=BaseModel)


class LLMError(RuntimeError):
    """Shown to the user as is, so the message is in Romanian."""


@dataclass(frozen=True)
class Parsed(Generic[T]):
    output: T
    model: str  # the model that actually answered (differs after a fallback)
    input_tokens: int
    output_tokens: int


def make_client(keys: KeyStore) -> anthropic.Anthropic:
    api_key = keys.get(ANTHROPIC_API_KEY)
    if not api_key:
        raise LLMError("Lipsește cheia Anthropic: adaug-o pe pagina „Chei API” sau în .env.")
    return anthropic.Anthropic(api_key=api_key)


def parse(
    client: Any,
    *,
    llm: LLMConfig,
    output_format: type[T],
    system: str,
    content: list[dict[str, Any]],
    what: str,
) -> Parsed[T]:
    """Ask Claude for `output_format`; every failure becomes an LLMError. `what` names the
    result in the messages ("acest CV", "profilul")."""
    request: dict[str, Any] = {
        "model": llm.model,
        "max_tokens": llm.max_tokens,
        "output_config": {"effort": llm.effort},
        "output_format": output_format,
        "system": system,
        "messages": [{"role": "user", "content": content}],
    }
    if llm.model in FALLBACK_MODELS:
        request |= {"betas": [FALLBACK_BETA], "fallbacks": "default"}

    try:
        response = client.beta.messages.parse(**request)
    except anthropic.AuthenticationError as exc:
        raise LLMError("Anthropic a respins cheia API. Verifică ANTHROPIC_API_KEY.") from exc
    except anthropic.PermissionDeniedError as exc:
        raise LLMError("Cheia Anthropic nu are acces la acest model.") from exc
    except anthropic.RateLimitError as exc:
        raise LLMError("Ai atins limita de cereri Anthropic; încearcă din nou peste un minut.") from exc
    except anthropic.BadRequestError as exc:
        raise LLMError(f"Cererea către Claude a fost respinsă: {exc.message}") from exc
    except anthropic.APIStatusError as exc:
        raise LLMError(f"Eroare Anthropic ({exc.status_code}); încearcă din nou mai târziu.") from exc
    except anthropic.APIConnectionError as exc:
        raise LLMError("Nu am putut contacta Anthropic; verifică conexiunea la internet.") from exc

    if response.stop_reason == "refusal":
        raise LLMError(f"Claude a refuzat să genereze {what}.")
    if response.stop_reason == "max_tokens":
        raise LLMError("Răspunsul a fost tăiat (llm.max_tokens din config.yaml e prea mic).")
    if response.parsed_output is None:
        raise LLMError(f"Claude nu a întors {what} într-un format valid; încearcă din nou.")

    log.info(
        "%s generated by %s (%d in / %d out tokens, %d from cache)",
        output_format.__name__,
        response.model,
        response.usage.input_tokens,
        response.usage.output_tokens,
        getattr(response.usage, "cache_read_input_tokens", 0) or 0,
    )
    return Parsed(
        output=response.parsed_output,
        model=response.model,
        input_tokens=response.usage.input_tokens,
        output_tokens=response.usage.output_tokens,
    )
